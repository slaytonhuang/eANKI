    /** 這段文字裡確定是簡體的字，去重後依出現順序回傳。 */
    @NonNull
    public static List<Character> find(@Nullable String text) {
        List<Character> found = new ArrayList<>();
        if (text == null) {
            return found;
        }
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            if (SIMPLIFIED_ONLY.indexOf(c) >= 0 && !found.contains(c)) {
                found.add(c);
            }
        }
        return found;
    }

    public static boolean hasSimplified(@Nullable String text) {
        return !find(text).isEmpty();
    }

